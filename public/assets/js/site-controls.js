  function translateTextNode(node) {
    if (!originalText.has(node)) {
      originalText.set(node, { source: node.nodeValue, output: node.nodeValue });
    }

    const record = originalText.get(node);
    if (node.nodeValue !== record.output) record.source = node.nodeValue;
    const translated = localizedValue(record.source, language);
    const output = translated === null ? record.source : translated;
    record.output = output;

    if (node.nodeValue !== output) node.nodeValue = output;
  }

  function translateAttribute(element, attribute) {
    const value = element.getAttribute(attribute);
    if (value === null) return;

    let records = originalAttributes.get(element);
    if (!records) {
      records = new Map();
      originalAttributes.set(element, records);
    }

    if (!records.has(attribute)) records.set(attribute, { source: value, output: value });
    const record = records.get(attribute);
    if (value !== record.output) record.source = value;
    const translated = localizedValue(record.source, language);
    const output = translated === null ? record.source : translated;
    record.output = output;
    if (value !== output) element.setAttribute(attribute, output);
  }

  function translateTree(root) {
    if (!root) return;

    const elements = [];
    if (root.nodeType === Node.ELEMENT_NODE) elements.push(root);
    if (typeof root.querySelectorAll === 'function') elements.push(...root.querySelectorAll('*'));
    elements.forEach(element => {
      ['aria-label', 'placeholder', 'title', 'alt'].forEach(attribute => translateAttribute(element, attribute));
    });

    if (root.nodeType === Node.TEXT_NODE) {
      translateTextNode(root);
      return;
    }

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();
    while (node) {
      if (!node.parentElement.closest('script, style, noscript, svg')) translateTextNode(node);
      node = walker.nextNode();
    }
  }

