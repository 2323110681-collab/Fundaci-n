// El motor de voz ignora utterance.lang cuando no se le asigna una voz concreta:
// usa entonces la del sistema, que suele estar en otro idioma. Ademas
// getVoices() devuelve una lista vacia hasta que el navegador termina de
// cargarla, por eso hay que esperar al evento voiceschanged.
function loadVoices() {
  return new Promise(resolve => {
    if (!('speechSynthesis' in window)) {
      resolve([]);
      return;
    }
    const available = window.speechSynthesis.getVoices();
    if (available.length) {
      resolve(available);
      return;
    }
    let settled = false;
    const finish = () => {
      if (settled) return;
      settled = true;
      window.speechSynthesis.removeEventListener('voiceschanged', finish);
      resolve(window.speechSynthesis.getVoices());
    };
    window.speechSynthesis.addEventListener('voiceschanged', finish);
    // Algunos navegadores nunca emiten voiceschanged: se resuelve igual tras un
    // corto margen para no dejar el altavoz sin responder.
    setTimeout(finish, 1000);
  });
}

function pickVoice(voices, lang) {
  if (!voices || !voices.length) return null;
  const target = lang.toLowerCase();
  const base = target.split('-')[0];
  const normalize = voice => voice.lang.toLowerCase().replace('_', '-');
  const exact = voices.find(voice => normalize(voice) === target);
  if (exact) return exact;
  // Sin coincidencia exacta se acepta cualquier voz del mismo idioma, prefiriendo
  // la que ya esta instalada en el equipo: es la que suena sin descargar nada.
  const sameLanguage = voices.filter(voice => normalize(voice).split('-')[0] === base);
  return sameLanguage.find(voice => voice.localService) || sameLanguage[0] || null;
}

