  function formatLocalizedDate(day, month, year, weekday, short, targetLanguage) {
    if (targetLanguage === 'en') {
      const monthName = short ? englishShortMonths[month - 1] : englishMonths[month - 1];
      const prefix = weekday === null ? '' : `${englishWeekdays[weekday]}, `;
      return `${prefix}${monthName} ${day}, ${year}`;
    }
    const suffix = weekday === null ? '' : ` ${chineseWeekdays[weekday]}`;
    return `${year}年${month}月${day}日${suffix}`;
  }

  // Fechas generadas por el sitio en español: "28 de septiembre de 2026", "lunes, 28 de septiembre de 2026" y "28 sept 2026".
  function localizeSpanishDate(text, targetLanguage) {
    const plain = removeAccents(text.trim().toLowerCase());
    const longDate = plain.match(/^(?:(domingo|lunes|martes|miercoles|jueves|viernes|sabado),?\s+)?(\d{1,2}) de (enero|febrero|marzo|abril|mayo|junio|julio|agosto|septiembre|setiembre|octubre|noviembre|diciembre) de (\d{4})$/);
    if (longDate) {
      const weekday = longDate[1] ? spanishWeekdays[longDate[1]] : null;
      return formatLocalizedDate(Number(longDate[2]), spanishMonths[longDate[3]], longDate[4], weekday, false, targetLanguage);
    }
    const shortDate = plain.match(/^(\d{1,2}) (?:de )?(ene|feb|mar|abr|may|jun|jul|ago|sept|sep|set|oct|nov|dic)\.? (?:de )?(\d{4})$/);
    if (shortDate) {
      return formatLocalizedDate(Number(shortDate[1]), spanishShortMonths[shortDate[2]], shortDate[3], null, true, targetLanguage);
    }
    return null;
  }

